export default function Sidebar() {
  const { user, logout } = useAuth()
  const navigate = useNavigate()

  const navItems = user?.user_type === 'patient' ? patientNav : staffNav

  // Resolve the display name from whichever profile shape is present
  const displayName = isPatientProfile(user?.profile)
    ? user.profile.full_name
    : isStaffProfile(user?.profile)
      ? user.profile.full_name
      : user?.email

  async function handleLogout() {
    await logout()
    toast.success('Logged out')
    navigate('/login')
  }

  return (
    <aside className="flex h-screen w-64 shrink-0 flex-col border-r border-gray-200 bg-white">
      {/* Logo */}
      <div className="flex items-center gap-2 px-6 py-5 border-b border-gray-100">
        <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-primary-600">
          <svg className="h-5 w-5 text-white" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M4.318 6.318a4.5 4.5 0 000 6.364L12 20.364l7.682-7.682a4.5 4.5 0 00-6.364-6.364L12 7.636l-1.318-1.318a4.5 4.5 0 00-6.364 0z" />
          </svg>
        </div>
        <span className="text-base font-bold text-gray-900">OneHealth</span>
      </div>

      {/* Nav */}
      <nav className="flex-1 overflow-y-auto px-3 py-4 space-y-1">
        {navItems.map((item) => (
          <NavItemEl key={item.to} item={item} />
        ))}
      </nav>

      {/* User + Logout */}
      <div className="border-t border-gray-200 p-4">
        <div className="flex items-center gap-3 mb-3">
          <div className="flex h-8 w-8 items-center justify-center rounded-full bg-primary-100 text-primary-700 text-sm font-semibold">
            {displayName?.[0]?.toUpperCase() ?? '?'}
          </div>
          <div className="min-w-0">
            <p className="truncate text-sm font-medium text-gray-900">
              {displayName ?? user?.email}
            </p>
            <p className="text-xs text-gray-500 capitalize">{user?.user_type?.replace('_', ' ')}</p>
          </div>
        </div>
        <button onClick={handleLogout} className="btn-secondary w-full text-sm">
          Sign out
        </button>
      </div>
    </aside>
  )
}
